# ─── Data ───────────────────────────────────────────────────────────────────


@dataclass
class Dataset:
    domain: np.ndarray    # object arrays of str, one entry per row
    label: np.ndarray     # the registrable label: what the features describe
    suffix: np.ndarray    # its public suffix
    tld: np.ndarray       # the suffix's last label
    name: np.ndarray      # the registrable domain: label + public suffix
    y: np.ndarray         # 1: generated by a DGA
    family: np.ndarray
    kind: np.ndarray      # benign, dga or dictionary
    date: np.ndarray      # the day a generated name belongs to ("" if not seeded by date)
    source: np.ndarray    # tranco, bader or netlab
    external: np.ndarray  # from external_netlab.csv: only ever tested on
    blocked: np.ndarray   # on the blocklist snapshot
    base: np.ndarray      # every feature, with the fitted ones (groups B, E) still zero

    def __len__(self) -> int:
        return len(self.y)

    def concat(self, other: "Dataset") -> "Dataset":
        return Dataset(**{f: np.concatenate([getattr(self, f), getattr(other, f)]) for f in self.__dataclass_fields__})

    def take(self, rows: np.ndarray) -> "Dataset":
        return Dataset(**{f: getattr(self, f)[rows] for f in self.__dataclass_fields__})


def load(path: Path, context: FeatureContext, blocked: set[str], benign: str, fraction: float, seed: int,
         external: bool = False) -> Dataset:
    rows = read_csv(path)
    if benign == "stable":
        rows = [row for row in rows if row["label"] == 1 or row["stable"]]
    if fraction < 1:  # the same share of every family
        rng = np.random.default_rng(seed)
        by_family: dict[str, list[int]] = {}
        for i, row in enumerate(rows):
            by_family.setdefault(row["family"], []).append(i)
        keep = sorted(j for members in by_family.values()
                      for j in rng.choice(members, max(1, math.ceil(fraction * len(members))), replace=False))
        rows = [rows[i] for i in keep]
    psl = default_list()
    columns: dict[str, list] = {f: [] for f in Dataset.__dataclass_fields__}
    for row in rows:
        label, suffix = split_name(row["domain"], psl)
        name = f"{label}.{suffix}" if suffix else label
        columns["domain"].append(row["domain"])
        columns["label"].append(label)
        columns["suffix"].append(suffix)
        columns["tld"].append(suffix.rsplit(".", 1)[-1])
        columns["name"].append(name)
        columns["blocked"].append(row["domain"] in blocked or name in blocked)
        columns["base"].append(label_features(label, suffix, context).vector())
        for f in ("family", "kind", "date", "source"):
            columns[f].append(row[f])
        columns["y"].append(row["label"])
    numeric = ("y", "blocked", "base", "external")
    arrays = {f: np.array(v, dtype=object) for f, v in columns.items() if f not in numeric}
    return Dataset(**arrays, y=np.array(columns["y"], dtype=np.int8), blocked=np.array(columns["blocked"], dtype=bool),
                   external=np.full(len(rows), external),
                   base=np.array(columns["base"], dtype=float).reshape(len(rows), len(NAMES)))


def read_lines(path: Path) -> list[str]:
    return [line.strip() for line in path.read_text().splitlines() if line.strip()] if path.exists() else []


def allowlist_labels(path: Path) -> frozenset[str]:
    """The registrable labels of the allowlisted names (feature F): google for google.com."""
    psl = default_list()
    labels = set()
    for domain in read_lines(path):
        try:
            labels.add(split_name(domain, psl)[0])
        except ValueError:
            pass
    return frozenset(labels)


def parse_groups(text: str) -> list[str]:
    groups = sorted({g.strip().upper() for g in text.split(",") if g.strip()})
    unknown = [g for g in groups if g not in FEATURE_GROUPS]
    if unknown or not groups:
        raise SystemExit(f"--features: groups are {', '.join(FEATURE_GROUPS)} (got {text!r})")
    return groups


# ─── Splits ─────────────────────────────────────────────────────────────────


@dataclass
class Split:
    name: str
    train: np.ndarray
    test: np.ndarray


@dataclass
class SplitResult:
    split: Split
    scores: dict[str, np.ndarray] = field(default_factory=dict)
    thresholds: dict[str, float] = field(default_factory=dict)
    fit_seconds: dict[str, float] = field(default_factory=dict)
    fitted: dict[str, models.Model] = field(default_factory=dict)
    fitted_features: dict = field(default_factory=dict)  # the n-gram models and TLD prior behind the features


def benign_holdout(data: Dataset, share: float, seed: int) -> tuple[np.ndarray, np.ndarray]:
    """A fixed split of the benign names into training and test."""
    benign = np.random.default_rng(seed).permutation(np.flatnonzero((data.y == 0) & ~data.external))
    cut = int(round(len(benign) * (1 - share)))
    return np.sort(benign[:cut]), np.sort(benign[cut:])


def splits_for(mode: str, data: Dataset, args) -> list[Split]:
    ours = ~data.external
    dga = (data.kind == "dga") & ours
    if mode == "cv":
        from sklearn.model_selection import StratifiedKFold

        rows = np.flatnonzero(((data.y == 0) | dga) & ours)
        folds = StratifiedKFold(args.folds, shuffle=True, random_state=args.seed)
        return [Split(f"fold {k + 1}", np.sort(rows[train]), np.sort(rows[test]))
                for k, (train, test) in enumerate(folds.split(rows, data.family[rows].astype(str)))]
    b_train, b_test = benign_holdout(data, args.benign_test, args.seed)
    if mode == "lofo":
        return [Split(family, np.concatenate([b_train, np.flatnonzero(dga & (data.family != family))]),
                      np.concatenate([b_test, np.flatnonzero(dga & (data.family == family))]))
                for family in sorted(set(data.family[dga]))]
    if mode == "dictionary":
        return [Split("dictionary", np.concatenate([b_train, np.flatnonzero(dga)]),
                      np.concatenate([b_test, np.flatnonzero((data.kind == "dictionary") & ours)]))]
    if mode == "future":
        dated = dga & (data.date != "")
        before = dated & (data.date < args.cutoff)
        return [Split(f"before {args.cutoff}", np.concatenate([b_train, np.flatnonzero(before)]),
                      np.concatenate([b_test, np.flatnonzero(dated & ~before)]))]
    if mode == "external":
        return [Split("netlab", np.concatenate([b_train, np.flatnonzero(dga)]),
                      np.concatenate([b_test, np.flatnonzero(data.external)]))]
    if mode == "final":
        return [Split("final", np.flatnonzero(((data.y == 0) | dga) & ours), np.array([], dtype=int))]
    raise ValueError(mode)


class Features:
    """Feature matrices with the fitted columns filled in for a split's training names."""

    def __init__(self, data: Dataset, context: FeatureContext, bigrams: bool, keep: int = 1,
                 rhythm: bool = False) -> None:
        log("indexing n-grams")
        self.data, self.context = data, context
        self.trigrams = GramIndex(data.label, 3)
        self.bigrams = GramIndex(data.label, 2) if bigrams else None
        self.shapes = GramIndex([shape(label) for label in data.label], 4) if rhythm else None
        self.keep, self._cache = keep, {}  # tuning revisits the same splits: keep their matrices

    def matrix(self, fit: np.ndarray) -> tuple[np.ndarray, dict]:
        key = hashlib.sha1(np.ascontiguousarray(fit).tobytes()).hexdigest()
        if key not in self._cache:
            while len(self._cache) >= self.keep:
                self._cache.pop(next(iter(self._cache)))
            self._cache[key] = self._compute(fit)
        return self._cache[key]

    def _compute(self, fit: np.ndarray) -> tuple[np.ndarray, dict]:
        data = self.data
        benign, dga = fit[data.y[fit] == 0], fit[data.y[fit] == 1]
        X = data.base.copy()
        fitted: dict = {"ngram": self.trigrams.fit(benign), "tld_prior": TldPrior().fit(data.suffix[benign])}
        X[:, COLUMN["ngram_log_likelihood"]] = fitted["ngram"].score()
        tlds, where = np.unique(data.tld.astype(str), return_inverse=True)
        X[:, COLUMN["tld_log_share"]] = np.array([fitted["tld_prior"].score(t) for t in tlds])[where]
        if self.bigrams is not None and len(dga):
            fitted["bigram"] = self.bigrams.fit(benign)
            fitted["dga_ngram"] = self.trigrams.fit(dga)
            X[:, COLUMN["bigram_log_likelihood"]] = fitted["bigram"].score()
            X[:, COLUMN["dga_likelihood_ratio"]] = X[:, COLUMN["ngram_log_likelihood"]] - fitted["dga_ngram"].score()
        if self.shapes is not None:
            fitted["rhythm"] = self.shapes.fit(benign)
            X[:, COLUMN["rhythm_log_likelihood"]] = fitted["rhythm"].score()
        return X, fitted

    def context_for(self, fitted: dict) -> FeatureContext:
        """The FeatureContext that computes the same features one name at a time."""
        as_model = {k: (v.model() if isinstance(v, FittedGrams) else v) for k, v in fitted.items()}
        return FeatureContext(ngram=as_model["ngram"], tld_prior=as_model["tld_prior"], words=self.context.words,
                              bigram=as_model.get("bigram"), dga_ngram=as_model.get("dga_ngram"),
                              allow_labels=self.context.allow_labels, rhythm=as_model.get("rhythm"))


def batch(data: Dataset, X: np.ndarray, columns: list[int], rows: np.ndarray,
          weight: np.ndarray | None = None) -> models.Batch:
    return models.Batch(X[np.ix_(rows, columns)], data.name[rows], data.blocked[rows], data.y[rows],
                        X[rows, COLUMN["entropy"]], weight)


def family_weights(data: Dataset, rows: np.ndarray, balance: float) -> np.ndarray | None:
    """Training weights that even out the DGA families: (median size / family size) ** balance.

    0 leaves every name at weight 1; 1 gives every family the same total
    weight. DGA weights are scaled to keep their sum, benign names stay at 1.
    """
    if not balance:
        return None
    weights = np.ones(len(rows))
    dga = data.y[rows] == 1
    _, where, counts = np.unique(data.family[rows][dga].astype(str), return_inverse=True, return_counts=True)
    raw = (np.median(counts) / counts[where]) ** balance
    weights[dga] = raw * (dga.sum() / raw.sum())
    return weights


def run_split(data: Dataset, split: Split, names: list[str], features: Features, columns: list[int], args) -> SplitResult:
    result = SplitResult(split)
    benign = split.train[data.y[split.train] == 0]
    calibration = np.sort(np.random.default_rng(args.seed).choice(
        benign, max(1, int(len(benign) * args.calibration)), replace=False))
    fit = np.setdiff1d(split.train, calibration)
    X, result.fitted_features = features.matrix(fit)
    weight = family_weights(data, fit, args.params.get("family_balance", 0.0))
    for name in names:
        model = models.make(name, args.seed, args.threads, args.params.get(name))
        started = time.monotonic()
        model.fit(batch(data, X, columns, fit, weight))
        result.fit_seconds[name] = time.monotonic() - started
        if model.fixed_threshold is not None:
            result.thresholds[name] = model.fixed_threshold
        else:
            result.thresholds[name] = metrics.threshold_at_fpr(model.score(batch(data, X, columns, calibration)),
                                                               args.fpr)
        result.scores[name] = model.score(batch(data, X, columns, split.test)) if len(split.test) else np.array([])
        result.fitted[name] = model
    return result


# ─── Reports ────────────────────────────────────────────────────────────────


def kinds_of(data: Dataset, rows: np.ndarray) -> dict[str, str]:
    return {str(f): str(k) for f, k in zip(data.family[rows], data.kind[rows])}


def evaluate(data: Dataset, rows: np.ndarray, score: np.ndarray, decision: np.ndarray, args, rng) -> dict:
    return metrics.evaluate(data.y[rows], score, decision, data.family[rows].astype(str), args.fpr, rng,
                            args.bootstrap, args.bootstrap_curve, kinds_of(data, rows))


def compare(names: list[str], correct: dict[str, np.ndarray]) -> dict:
    """McNemar's test of the first model against each of the others."""
    first = names[0]
    return {f"{first} vs {other}": metrics.mcnemar(correct[first], correct[other]) for other in names[1:]}


def report_pooled(data: Dataset, results: list[SplitResult], names: list[str], args, rng) -> dict:
    """One evaluation over every split's test rows together (each row is tested once)."""
    rows = np.concatenate([r.split.test for r in results])
    report, correct = {"models": {}}, {}
    for name in names:
        score = np.concatenate([r.scores[name] for r in results])
        decision = np.concatenate([r.scores[name] > r.thresholds[name] for r in results])
        log(f"evaluating {name}")
        report["models"][name] = evaluate(data, rows, score, decision, args, rng)
        report["models"][name]["thresholds"] = [r.thresholds[name] for r in results]
        report["models"][name]["fit_seconds"] = sum(r.fit_seconds[name] for r in results)
        if len(results) > 1:  # spread across folds, without the bootstrap
            per_split = [metrics.evaluate(data.y[r.split.test], r.scores[name], r.scores[name] > r.thresholds[name],
                                          data.family[r.split.test].astype(str), args.fpr, rng, 1, 1)
                         for r in results]
            report["models"][name]["per_split"] = {
                key: {"mean": statistics.mean(m[key]["value"] for m in per_split),
                      "stdev": statistics.stdev(m[key]["value"] for m in per_split)}
                for key in ("recall", "fpr", "roc_auc", "pr_auc", "recall_at_target_fpr", "recall_at_1pct_fpr")
                if key in per_split[0]}
        correct[name] = decision == data.y[rows].astype(bool)
    report["mcnemar"] = compare(names, correct)
    return report


def report_lofo(data: Dataset, results: list[SplitResult], names: list[str], args, rng) -> dict:
    """Each family tested on its own (against the same benign test names)."""
    report = {"families": {}, "models": {}}
    for r in results:
        rows = r.split.test
        report["families"][r.split.name] = {
            name: evaluate(data, rows, r.scores[name], r.scores[name] > r.thresholds[name], args, rng)
            for name in names}
        log(f"  {r.split.name:20} " + "  ".join(
            f"{n} {report['families'][r.split.name][n]['recall']['value']:.3f}" for n in names))
    correct = {}
    for name in names:
        per_family = [report["families"][f][name] for f in report["families"]]
        recalls = [m["recall"]["value"] for m in per_family]
        report["models"][name] = {
            "mean_recall": statistics.mean(recalls),
            "median_recall": statistics.median(recalls),
            "mean_recall_at_target_fpr": statistics.mean(m.get("recall_at_target_fpr", {}).get("value", 0.0)
                                                         for m in per_family),
            "mean_recall_at_1pct_fpr": statistics.mean(m.get("recall_at_1pct_fpr", {}).get("value", 0.0)
                                                       for m in per_family),
            "mean_roc_auc": statistics.mean(m.get("roc_auc", {}).get("value", math.nan) for m in per_family),
            "mean_fpr": statistics.mean(m["fpr"]["value"] for m in per_family),
            "families_below_90": sorted(f for f, m in zip(report["families"], per_family)
                                        if m["recall"]["value"] < 0.9),
        }
        # McNemar on the held-out DGA names only: the benign names repeat in every split.
        correct[name] = np.concatenate([(r.scores[name] > r.thresholds[name])[data.y[r.split.test] == 1]
                                        for r in results])
    report["mcnemar_on_unseen_families"] = compare(names, correct)
    return report


def measure(result: SplitResult, data: Dataset, features: Features, columns: list[int], args) -> dict:
    """Size of each fitted model, and the time to score one new name end to end
    (split, every feature, model) in Python. The C++ fast path is E9's."""
    rng = np.random.default_rng(args.seed)
    pool = result.split.test if len(result.split.test) else result.split.train
    domains = data.domain[rng.choice(pool, min(1000, len(pool)), replace=False)]
    psl, context = default_list(), features.context_for(result.fitted_features)
    blocked = set(data.name[data.blocked])
    out = {}
    for name, model in result.fitted.items():
        model.single_thread()  # one name at a time, as the resolver scores them
        times = []
        for domain in domains:
            started = time.perf_counter_ns()
            label, suffix = split_name(domain, psl)
            registrable = f"{label}.{suffix}" if suffix else label
            vector = label_features(label, suffix, context).vector()
            x = np.array([[vector[c] for c in columns]])
            model.score(models.Batch(x, np.array([registrable], dtype=object),
                                     np.array([domain in blocked or registrable in blocked]), None,
                                     np.array([vector[COLUMN["entropy"]]])))
            times.append(time.perf_counter_ns() - started)
        times.sort()
        out[name] = {**model.size(), "latency_median_us": times[len(times) // 2] / 1000,
                     "latency_p99_us": times[int(0.99 * (len(times) - 1))] / 1000}
    return out


def table_t4(report: dict, sizes: dict, names: list[str], path: Path) -> None:
    """T4: the models side by side (pooled cross-validation)."""
    header = ["model", "roc_auc", "pr_auc", "recall_at_0.1%_fpr", "recall_at_1%_fpr", "recall", "fpr", "precision",
              "f1", "size_bytes", "trees", "nodes", "latency_median_us", "fit_seconds"]
    lines = [",".join(header)]
    markdown = ["| Model | ROC-AUC | PR-AUC | Recall @0.1% FPR | Recall @1% FPR | Recall | FPR | F1 | Size | Latency (µs) |",
                "|---|---|---|---|---|---|---|---|---|---|"]

    def cell(m, key, digits=4):
        value = m.get(key, {}).get("value")
        return "" if value is None or value != value else f"{value:.{digits}f}"

    for name in names:
        m, s = report["models"][name], sizes.get(name, {})
        lines.append(",".join(str(v) for v in [
            name, cell(m, "roc_auc"), cell(m, "pr_auc"), cell(m, "recall_at_target_fpr"),
            cell(m, "recall_at_1pct_fpr"), cell(m, "recall"), cell(m, "fpr", 5), cell(m, "precision"), cell(m, "f1"),
            s.get("bytes", ""), s.get("trees", ""), s.get("nodes", ""), f"{s.get('latency_median_us', 0):.1f}",
            f"{m.get('fit_seconds', 0):.1f}"]))
        size = s.get("bytes", 0)
        size_text = f"{size / 1e6:.1f} MB" if size >= 1e6 else f"{size / 1e3:.0f} kB" if size else "-"
        markdown.append(f"| {models.title(name)} | {cell(m, 'roc_auc')} | {cell(m, 'pr_auc')} | "
                        f"{cell(m, 'recall_at_target_fpr')} | {cell(m, 'recall_at_1pct_fpr')} | {cell(m, 'recall')} | "
                        f"{cell(m, 'fpr', 5)} | {cell(m, 'f1')} | {size_text} | {s.get('latency_median_us', 0):.0f} |")
    path.with_suffix(".csv").write_text("\n".join(lines) + "\n")
    path.with_suffix(".md").write_text("\n".join(markdown) + "\n")


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else ""


def save_final(result: SplitResult, data: Dataset, features: Features, groups: list[str], out: Path, args) -> dict:
    """The deployed model: LightGBM trees, the fitted feature models and the threshold."""
    result.fitted["lgbm"].model.booster_.save_model(str(out / "dga_lgbm.txt"))
    context = features.context_for(result.fitted_features)
    tables = {"ngram": context.ngram.state(), "tld_prior": context.tld_prior.state()}
    if context.bigram:
        tables.update(bigram=context.bigram.state(), dga_ngram=context.dga_ngram.state())
    if context.rhythm:
        tables.update(rhythm=context.rhythm.state())
    (out / "features.json").write_text(json.dumps(tables) + "\n")
    rows = result.split.train
    card = {
        "features": [n for g in groups for n in FEATURE_GROUPS[g]],
        "groups": groups,
        "threshold": result.thresholds["lgbm"],
        "target_fpr": args.fpr,
        "trained_on": {"benign": int((data.y[rows] == 0).sum()), "dga": int((data.y[rows] == 1).sum()),
                       "benign_set": args.benign,
                       "families": sorted(set(data.family[rows][data.y[rows] == 1].astype(str)))},
        "psl_version": default_list().version,
        "words_sha256": _sha256(WORDS_PATH),
        "allowlist_sha256": _sha256(args.data / "allowlist_top100k.txt"),
        "lightgbm_params": result.fitted["lgbm"].params,
    }
    (out / "model.json").write_text(json.dumps(card, indent=1) + "\n")
    return card


