def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True,
                              timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def environment() -> dict:
    versions = {"python": platform.python_version()}
    for module in ("numpy", "sklearn", "lightgbm", "torch", "matplotlib"):
        try:
            versions[module] = __import__(module).__version__
        except ImportError:
            pass
    gpu = ""
    if "torch" in versions:
        import torch

        gpu = torch.cuda.get_device_name(0) if torch.cuda.is_available() else ""
    return {"host": platform.node(), "platform": platform.platform(), "cpus": os.cpu_count(), "gpu": gpu,
            "versions": versions, "git_commit": _git_commit()}


def _clean(value):
    """JSON without NaN: missing values become null."""
    if isinstance(value, float) and value != value:
        return None
    if isinstance(value, dict):
        return {k: _clean(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_clean(v) for v in value]
    if isinstance(value, np.generic):
        return _clean(value.item())
    return value


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(_clean(value), indent=1) + "\n")


def headline(mode: str, report: dict) -> dict:
    if mode == "lofo":
        return {n: {k: (len(v) if isinstance(v, list) else v) for k, v in m.items()}
                for n, m in report["models"].items()}
    if mode == "final":
        return {"threshold": report["threshold"]}
    keys = ("roc_auc", "pr_auc", "recall_at_target_fpr", "recall_at_1pct_fpr", "recall", "fpr",
            "mean_family_recall_dga", "mean_family_recall_dictionary")
    return {n: {k: (m[k]["value"] if isinstance(m[k], dict) else m[k]) for k in keys if k in m}
            for n, m in report["models"].items()}


def run_mode(mode: str, data: Dataset, features: Features, groups: list[str], args) -> dict:
    started, clock = dt.datetime.now(dt.timezone.utc), time.monotonic()
    out = args.out / args.tag / f"f-{''.join(groups)}" / mode
    out.mkdir(parents=True, exist_ok=True)
    if mode == "final":  # the deployable model, whatever --models compares
        wanted = DEFAULT_MODELS["final"].split(",")
    else:
        wanted = (args.models or OTHER_MODELS).split(",")
        wanted += [n for n in args.add_models.split(",") if n and n not in wanted]
    names = [n for n in wanted if models.available(n)]
    for missing in sorted(set(wanted) - set(names)):
        log(f"skipping {missing}: its library is not installed")
    if mode == "final" and "lgbm" not in names:
        raise SystemExit("final mode trains lgbm: install lightgbm")
    columns = [COLUMN[n] for g in groups for n in FEATURE_GROUPS[g]]

    splits = splits_for(mode, data, args)
    rng = np.random.default_rng(args.seed)
    results = []
    for split in splits:
        log(f"{mode} [{''.join(groups)}]: {split.name} (train {len(split.train):,}, test {len(split.test):,})")
        results.append(run_split(data, split, names, features, columns, args))

    if mode == "final":
        report = save_final(results[0], data, features, groups, out, args)
        report["measured"] = measure(results[0], data, features, columns, args)
    elif mode == "lofo":
        report = report_lofo(data, results, names, args, rng)
    else:
        report = report_pooled(data, results, names, args, rng)
    report["settings"] = {"target_fpr": args.fpr, "calibration_share": args.calibration, "seed": args.seed,
                          "fraction": args.fraction, "bootstrap": args.bootstrap, "benign": args.benign,
                          "bootstrap_curve": args.bootstrap_curve, "features": groups,
                          "splits": [s.name for s in splits]}
    if mode == "future":
        report["settings"]["cutoff"] = args.cutoff
    if mode == "cv":
        report["measured"] = measure(results[-1], data, features, columns, args)
        table_t4(report, report["measured"], names, out / "T4_model_comparison")
    write_json(out / "metrics.json", report)

    if mode != "final":
        rows = np.concatenate([r.split.test for r in results])
        arrays = {"row": rows, "split": np.concatenate([np.full(len(r.split.test), i) for i, r in enumerate(results)]),
                  "y": data.y[rows], "family": data.family[rows].astype(str), "kind": data.kind[rows].astype(str),
                  "domain": data.domain[rows].astype(str)}
        for name in names:
            arrays[f"score_{name}"] = np.concatenate([r.scores[name] for r in results])
            arrays[f"threshold_{name}"] = np.concatenate([np.full(len(r.split.test), r.thresholds[name])
                                                          for r in results])
        np.savez_compressed(out / "scores.npz", **arrays)
        try:
            from . import plots

            if mode in ("cv", "dictionary", "future", "external"):
                plots.curves(out / "scores.npz", names, out / f"{'F8' if mode == 'cv' else 'curves'}_roc_pr.png",
                             args.fpr)
            if mode == "lofo":
                plots.lofo_heatmap(report, names, out / "F9_lofo_recall.png")
        except ImportError:
            log("matplotlib not installed: no figures")

    dataset_info = args.data / "dataset_info.json"
    info = {
        "mode": mode, "tag": args.tag, "features": groups, "benign": args.benign, "params": args.params,
        "started": started.isoformat(timespec="seconds"), "seconds": round(time.monotonic() - clock, 1),
        "models": names, "rows": len(data), "args": {k: str(v) for k, v in vars(args).items()},
        "dataset": json.loads(dataset_info.read_text()) if dataset_info.exists() else {},
        "dataset_sha256": _sha256(args.data / "dga_dataset.csv"),
        "environment": environment(), "headline": headline(mode, report),
    }
    write_json(out / f"run_info_{mode}.json", info)
    log(f"{mode} [{''.join(groups)}] done in {info['seconds']}s: {json.dumps(_clean(info['headline']))[:600]}")
    return info


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mode", choices=MODES + ["all", "tune"], required=True)
    parser.add_argument("--data", type=Path, default=REPO / "ml" / "data")
    parser.add_argument("--out", type=Path, default=REPO / "ml" / "runs")
    parser.add_argument("--tag", default="main", help="experiment name: results go to <out>/<tag>/")
    parser.add_argument("--features", nargs="+", default=["A,B,C,D,E"],  # F added nothing (ablation, 2026-10-18)
                        help="feature groups (features.py), e.g. A,B,C; several sets give one run each")
    parser.add_argument("--benign", choices=["stable", "all"], default="stable",
                        help="benign names: only those in Tranco a year ago too (default), or all")
    parser.add_argument("--models", help=f"comma-separated (default: {OTHER_MODELS})")
    parser.add_argument("--add-models", default="", help="added to every mode's models but final's (e.g. cnn)")
    parser.add_argument("--epochs", type=int, default=5, help="training epochs of the character CNN")
    parser.add_argument("--fraction", type=float, default=1.0, help="use this share of every family")
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--fpr", type=float, default=0.001, help="target false-positive rate")
    parser.add_argument("--calibration", type=float, default=0.1, help="share of benign training names held back")
    parser.add_argument("--benign-test", type=float, default=0.2, help="benign test share outside cv")
    parser.add_argument("--cutoff", default="2024-07-01", help="future mode: train before this date, test after")
    parser.add_argument("--bootstrap", type=int, default=1000)
    parser.add_argument("--bootstrap-curve", type=int, default=200, help="resamples for ROC/PR metrics")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--threads", type=int, default=os.cpu_count() or 1)
    parser.add_argument("--params", type=Path, help="JSON settings per model, e.g. tune mode's best_params.json")
    parser.add_argument("--trials", type=int, default=40, help="tune mode: settings to try")
    parser.add_argument("--timeout-hours", type=float, default=None,
                        help="tune mode: start no trial after this, shared by every feature set")
    parser.add_argument("--unseen-weight", type=float, default=0.5,
                        help="tune mode: weight of unseen-family recall in the objective (the rest: known families)")
    args = parser.parse_args(argv)
    args.params = json.loads(args.params.read_text()) if args.params else {}

    if not (args.data / "dga_dataset.csv").exists():
        raise SystemExit(f"no {args.data / 'dga_dataset.csv'}: run python -m ml.dga.data --out {args.data}")
    feature_sets = [parse_groups(text) for text in args.features]
    from . import charcnn  # imports PyTorch only when the CNN is made

    charcnn.OPTIONS["epochs"] = args.epochs
    modes = MODES if args.mode == "all" else [args.mode]
    blocked = set(read_lines(args.data / "blocklist_snapshot.txt"))
    if not blocked:
        log("no blocklist_snapshot.txt: the blocklist baseline flags nothing")
    context = FeatureContext(words=default_words(), allow_labels=allowlist_labels(args.data / "allowlist_top100k.txt"))
    log(f"loading {args.data / 'dga_dataset.csv'} ({args.benign} benign names)")
    data = load(args.data / "dga_dataset.csv", context, blocked, args.benign, args.fraction, args.seed)
    if "external" in modes:
        data = data.concat(load(args.data / "external_netlab.csv", context, blocked, args.benign, args.fraction,
                                args.seed, external=True))
    ours = ~data.external
    log(f"{len(data):,} names: {int((data.y == 0).sum()):,} benign, {int(((data.kind == 'dga') & ours).sum()):,} DGA "
        f"({len(set(data.family[(data.kind == 'dga') & ours]))} families), "
        f"{int(((data.kind == 'dictionary') & ours).sum()):,} dictionary, {int(data.external.sum()):,} external")
    features = Features(data, context, bigrams=any("E" in groups for groups in feature_sets),
                        keep=5 if args.mode == "tune" else 1, rhythm=any("G" in groups for groups in feature_sets))
    for groups in feature_sets:
        if args.mode == "tune":
            from .tune import tune

            tune(data, features, groups, args, len(feature_sets))
            continue
        for mode in modes:
            run_mode(mode, data, features, groups, args)


if __name__ == "__main__":
    sys.exit(main())
