"""Training and evaluating the DGA classifier: EVALUATION.md E7.

    python -m ml.dga.data --out ml/data            # build the data first
    python -m ml.dga.pipeline --mode cv            # stratified 5-fold: F8, T4
    python -m ml.dga.pipeline --mode lofo          # leave-family-out: F9
    python -m ml.dga.pipeline --mode dictionary    # dictionary families, never trained on
    python -m ml.dga.pipeline --mode future        # train before a date, test after it
    python -m ml.dga.pipeline --mode external      # Netlab 360's real names of families we generate
    python -m ml.dga.pipeline --mode final         # the model the resolver ships
    python -m ml.dga.pipeline --mode all
    python -m ml.dga.pipeline --mode lofo --features A A,B A,B,C,D,E,F   # one run per feature set
    python -m ml.dga.leaderboard ml/runs           # every run so far, side by side
    python -m ml.dga.pipeline --mode tune --models lgbm --trials 40   # tune.py: phase 3
    python -m ml.dga.pipeline --mode lofo --params best_params.json   # ...then use what it found

Each run writes ml/runs/<tag>/f-<groups>/<mode>/: metrics.json (every
metric, with bootstrap 95% intervals), scores.npz (every test score, for
re-plotting), run_info_<mode>.json (what ran, where, and the headline
numbers) and its figures. --fraction 0.05 runs on a 5% sample.

Benign names are the stable ones (--benign stable: in Tranco a year ago
too) unless --benign all. Every split is run the same way (run_split):
1. 10% of the split's benign training names are held back for calibration.
2. The fitted features (groups B and E in features.py) are fitted on the
   other training names, which are scored leave-one-out: training names
   must not look more familiar to the models than new names will.
3. Each model is fitted, and its threshold set so that at most --fpr (0.1%)
   of the calibration names would be flagged.
4. The test names are scored and judged against that threshold.
Dictionary families are never trained on (E7 reports them separately).
"""

